export type StringKey = keyof (typeof STRINGS)['en'];

/** Resolves the app language: an explicit choice, else the browser's. */
export function resolveUiLanguage(setting: string): UiLanguage {
  const wanted = setting === 'auto' ? (chrome.i18n?.getUILanguage?.() ?? 'en') : setting;
  const base = wanted.toLowerCase().split(/[-_]/)[0];
  return (UI_LANGUAGES.find((language) => language.code === base)?.code ?? 'en') as UiLanguage;
}

export type Translate = (key: StringKey, params?: Record<string, string | number>) => string;

export function translator(language: UiLanguage): Translate {
  const table = STRINGS[language] as Record<string, string>;
  const fallback = STRINGS.en as Record<string, string>;
  return (key, params) => {
    let text = table[key] ?? fallback[key] ?? key;
    if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}
